import React from 'react';
import { Modal, TextInput } from 'react-native';
import { PrescriptionEditor } from '../PrescriptionEditor';
import { SetType, type PlannedExercise } from '@/models';
const { create, act } = require('react-test-renderer');
jest.mock('react-i18next', () => ({ useTranslation: () => ({ t: (key: string) => key }) }));
jest.mock('react-native-safe-area-context', () => ({ useSafeAreaInsets: () => ({ bottom: 0 }) }));
const set = { setType: SetType.NORMAL, targetRepsMin: 8, targetReps: 12, targetRIR: 2 };
const exercise: PlannedExercise = { exerciseId: 'press', order: 0, isEdited: false, sets: [set, { ...set }, { ...set }] };
const button = (tree: any, label: string, role?: string) => (tree.root.findAllByType(Modal)[0] ?? tree.root).findAll((node: any) => node.props.accessibilityLabel === label && typeof node.props.onPress === 'function' && (!role || node.props.accessibilityRole === role))[0];
const tap = async (tree: any, label: string, role?: string) => { await act(async () => button(tree, label, role).props.onPress()); };
it('edits 10/8/6 and independent effort from one open keypad without a native keyboard', async () => {
  const change = jest.fn(); let tree: any;
  await act(async () => { tree = create(<PrescriptionEditor exercise={exercise} restSeconds={150} onChangeSet={change} />); });
  expect(tree.root.findAll((node: any) => /^prescription-row-/.test(node.props.testID ?? '') && typeof node.type !== 'function')).toHaveLength(3);
  await tap(tree, 'train.reps 1');
  expect(tree.root.findAllByType(TextInput)).toHaveLength(0);
  for (const key of ['1', '0']) await tap(tree, key);
  await tap(tree, 'prescription.nextSet');
  expect(change).toHaveBeenLastCalledWith(0, { targetRepsMin: 10, targetReps: 10 });
  await tap(tree, '8'); await tap(tree, 'prescription.nextSet');
  expect(change).toHaveBeenLastCalledWith(1, { targetRepsMin: 8, targetReps: 8 });
  await tap(tree, '6');
  await tap(tree, 'RIR', 'tab');
  expect(change).toHaveBeenLastCalledWith(2, { targetRepsMin: 6, targetReps: 6 });
  const keypad = () => tree.root.findAllByProps({ testID: 'prescription-keypad' })[0].props.style.height;
  const height = keypad();
  expect(tree.root.findAllByProps({ testID: 'prescription-value-min' })[0].props.children).toBe(6);
  await tap(tree, '0'); await tap(tree, 'prescription.previousSet');
  expect(change).toHaveBeenLastCalledWith(2, { targetRIR: 0 });
  expect(keypad()).toBe(height);
  await tap(tree, '1');
  expect(tree.root.findAllByType(Modal)).toHaveLength(1);
  await act(async () => tree.root.findByType(Modal).props.onRequestClose());
  expect(change).toHaveBeenLastCalledWith(1, { targetRIR: 1 });
  expect(tree.root.findAllByType(Modal)).toHaveLength(0);
  await act(async () => tree.unmount());
});
it('preserves an untouched range, accepts independent bounds, and ignores a cleared draft', async () => {
  const change = jest.fn(); let tree: any;
  await act(async () => { tree = create(<PrescriptionEditor exercise={exercise} restSeconds={150} onChangeSet={change} />); });
  await tap(tree, 'train.reps 1'); await tap(tree, 'prescription.minReps', 'tab');
  expect(change).not.toHaveBeenCalled();
  await tap(tree, '6'); await tap(tree, 'prescription.maxReps', 'tab');
  expect(change).toHaveBeenLastCalledWith(0, { targetRepsMin: 6 });
  await tap(tree, '1'); await tap(tree, '0'); await tap(tree, 'RIR', 'tab');
  expect(change).toHaveBeenLastCalledWith(0, { targetReps: 10 });
  await tap(tree, 'train.reps', 'tab');
  await act(async () => button(tree, 'workout.eraseDigit').props.onLongPress());
  const calls = change.mock.calls.length;
  await act(async () => tree.root.findByType(Modal).props.onRequestClose());
  expect(change).toHaveBeenCalledTimes(calls);
  await act(async () => tree.unmount());
});
it('programs advanced types and failure without shrinking the keypad or inventing completed extensions', async () => {
  const change = jest.fn(); let tree: any;
  await act(async () => { tree = create(<PrescriptionEditor exercise={exercise} restSeconds={150} onChangeSet={change} />); });
  await tap(tree, 'prescription.setType 1');
  const height = tree.root.findAllByProps({ testID: 'prescription-keypad' })[0].props.style.height;
  for (const type of [SetType.MYO_REP, SetType.DROP_SET, SetType.REST_PAUSE, SetType.FAILURE]) {
    await tap(tree, `setType.${type}`);
    expect(change).toHaveBeenLastCalledWith(0, expect.objectContaining({ setType: type }));
  }
  expect(change).toHaveBeenLastCalledWith(0, { setType: SetType.FAILURE, targetRIR: 0 });
  await tap(tree, 'RIR', 'tab');
  expect(tree.root.findAllByProps({ testID: 'prescription-keypad' })[0].props.style.height).toBe(height);
  expect(button(tree, '2').props.disabled).toBe(true);
  expect(tree.root.findAllByProps({ testID: 'prescription-value-rir' })[0].props.children).toBe('0');
  await act(async () => tree.unmount());
});
it('edits rest and timed sets with the same compact keypad and keeps top singles fixed', async () => {
  const rest = jest.fn(), count = jest.fn(), change = jest.fn(); let tree: any;
  const timed = { ...exercise, sets: [{ ...set, targetDurationSeconds: 30 }, { ...set, targetDurationSeconds: 30 }] };
  await act(async () => { tree = create(<PrescriptionEditor exercise={timed} restSeconds={150} onChangeSet={change} onChangeRest={rest} onChangeCount={count} />); });
  await tap(tree, 'calendar.restSeconds'); await tap(tree, '0');
  await act(async () => tree.root.findByType(Modal).props.onRequestClose()); expect(rest).toHaveBeenCalledWith(0);
  await tap(tree, 'train.reps 2'); await tap(tree, '4'); await tap(tree, '5');
  await act(async () => tree.root.findByType(Modal).props.onRequestClose()); expect(change).toHaveBeenCalledWith(1, { targetDurationSeconds: 45 });
  await tap(tree, 'train.addSet'); expect(count).toHaveBeenCalledWith(3);
  await tap(tree, 'prescription.removeSet'); expect(count).toHaveBeenCalledWith(1);
  await act(async () => tree.update(<PrescriptionEditor exercise={{ ...exercise, sets: [{ ...set, setType: SetType.TOP_SINGLE }, set] }} restSeconds={150} onChangeSet={change} onChangeCount={count} />));
  expect(button(tree, 'train.reps 1').props.disabled).toBe(true);
  expect(button(tree, 'prescription.removeSet').props.disabled).toBe(true);
  await act(async () => tree.unmount());
});
